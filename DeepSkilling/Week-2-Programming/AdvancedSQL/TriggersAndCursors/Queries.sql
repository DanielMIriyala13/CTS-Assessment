DELIMITER $$

CREATE PROCEDURE ShowEmp()
BEGIN
	DECLARE f INT DEFAULT 0;
	DECLARE n VARCHAR(50);

	DECLARE c CURSOR FOR SELECT Name FROM Employee;
	DECLARE CONTINUE HANDLER FOR NOT FOUND SET f=1;

	OPEN c;

	a: LOOP
		FETCH c INTO n;
		IF f=1 THEN
			LEAVE a;
		END IF;
		SELECT n;
	END LOOP;

	CLOSE c;
END$$

DELIMITER ;

CALL ShowEmp();