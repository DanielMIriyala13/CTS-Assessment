USE CTSDB;

DELIMITER $$

CREATE FUNCTION AddNum(a INT,b INT)
RETURNS INT
DETERMINISTIC
BEGIN
	RETURN a+b;
END$$

DELIMITER ;

SELECT AddNum(10,20);

DELIMITER $$

CREATE FUNCTION GetCount(d VARCHAR(30))
RETURNS INT
DETERMINISTIC
BEGIN
	DECLARE c INT;
	SELECT COUNT(*) INTO c FROM Employee WHERE Dept=d;
	RETURN c;
END$$

DELIMITER ;

SELECT GetCount('HR');